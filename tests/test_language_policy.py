"""
Language policy regression check (CONTRIBUTING.md, "English development standard").

Project source code, tests, UI text and documentation must be written in English. This check
fails when a Turkish-specific letter (c-cedilla, g-breve, dotless i, o-umlaut, s-cedilla,
u-umlaut, their capitals, or capital dotted I) appears in a file in scope, outside the reviewed
exceptions below.

Limitations: Turkish written without these letters, and other languages, are not detected;
code review remains responsible for them. Historical reports, user data, credentials and
generated files are outside the scope (NOT_IN_SCOPE).

Exceptions are exact lines. The check therefore also guards the protected content (the
multilingual test fixtures): changing or removing an exception line fails the check until the
list is reviewed. The AI disclaimer and prompt page labels, deferred until Stage 9B-4 (decisions D1
and D3), are English since Stage 9B-4 step 10 and are no longer exceptions.
"""
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TURKISH_LETTERS = re.compile("[\u00e7\u011f\u0131\u00f6\u015f\u00fc\u00c7\u011e\u0130\u00d6\u015e\u00dc]")

# Directory trees scanned recursively (text files only)
SOURCE_TREES = ("app", "tests", "frontend/src")
TEXT_SUFFIXES = {".py", ".ts", ".tsx", ".js", ".jsx", ".css", ".html", ".json", ".md", ".txt"}
SKIP_DIRS = {"__pycache__", "node_modules", "dist", ".pytest_cache"}

# Single files scanned at the repository root and in frontend/
TOP_LEVEL_PATTERNS = ("*.md", "*.txt", "*.ini", "*.bat", "*.json", ".env.example", ".gitignore", ".gitattributes")
FRONTEND_TOP_LEVEL_PATTERNS = ("*.html", "*.json", "*.js", "*.ts")

NOT_IN_SCOPE = {
    "PRODUCT_READINESS.md": "Historical Stage 9A report; quotes original Turkish text.",
    "ENGLISH_MIGRATION_PLAN.md": "Historical migration record; quotes the original Turkish text.",
    "ENGLISH_MIGRATION_VERIFICATION.md": "Historical migration record; quotes the original Turkish text.",
    "ENGLISH_MIGRATION_FINAL.md": "Historical migration record; quotes the original Turkish text.",
    "access_control.json": "Local access configuration (user data, not in version control).",
    "frontend/package-lock.json": "Generated by npm.",
}

EXCEPTION_REASONS = {
    "tests/test_document_storage.py":
        "Multilingual fixture (D4): non-ASCII user filename for Content-Disposition encoding.",
    "tests/test_documents.py":
        "Multilingual fixture (D4): non-ASCII document titles in rejected-upload tests.",
    "tests/test_review.py":
        "Multilingual fixture (D4): non-ASCII reviewer notes and corrections must round-trip unchanged.",
}

# Reviewed lines that may contain Turkish letters: (path, stripped line). Escaped so that this
# file itself stays ASCII.
ALLOWED_LINES = [
    ('tests/test_document_storage.py',
     'nasty = "\xdcnl\xfc belge; x=1.pdf"'),
    ('tests/test_documents.py',
     'data={"document_type": "other", "title": "Yanl\u0131\u015f Tip"},'),
    ('tests/test_documents.py',
     'data={"document_type": "other", "title": "B\xfcy\xfck Dosya"},'),
    ('tests/test_review.py',
     '"correction_note": "Prospekt\xfcs g\xfcncellemesine g\xf6re sabit getiri oran\u0131 belirlendi.",'),
    ('tests/test_review.py',
     'json={"corrected_value": "De\u011fi\u015fiklik denemesi.", "is_unknown": False},'),
    ('tests/test_review.py',
     'json={"notes": "T\xfcm alanlar ihra\xe7c\u0131 belgesiyle uyumlu."},'),
    ('tests/test_review.py',
     'assert body["notes"] == "T\xfcm alanlar ihra\xe7c\u0131 belgesiyle uyumlu."'),
    ('tests/test_review.py',
     'json={"corrected_value": "G\xfcncellenmi\u015f de\u011fer.", "is_unknown": False, **_same_evidence(claim)},'),
    ('tests/test_review.py',
     'assert corrections[0]["corrected_value"] == "G\xfcncellenmi\u015f de\u011fer."'),
]


def files_in_scope() -> list[Path]:
    found: set[Path] = set()
    for tree in SOURCE_TREES:
        for path in (ROOT / tree).rglob("*"):
            if path.is_file() and path.suffix in TEXT_SUFFIXES and not SKIP_DIRS & set(path.relative_to(ROOT).parts):
                found.add(path)
    for base, patterns in ((ROOT, TOP_LEVEL_PATTERNS), (ROOT / "frontend", FRONTEND_TOP_LEVEL_PATTERNS)):
        for pattern in patterns:
            found.update(p for p in base.glob(pattern) if p.is_file())
    return sorted(p for p in found if p.relative_to(ROOT).as_posix() not in NOT_IN_SCOPE)


def turkish_lines() -> tuple[Counter, dict]:
    counts: Counter = Counter()
    locations: dict = {}
    for path in files_in_scope():
        rel = path.relative_to(ROOT).as_posix()
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if TURKISH_LETTERS.search(line):
                key = (rel, line.strip())
                counts[key] += 1
                locations.setdefault(key, []).append(number)
    return counts, locations


def test_language_check_scope_covers_the_project():
    scanned = {p.relative_to(ROOT).as_posix() for p in files_in_scope()}
    for tree in SOURCE_TREES:
        assert any(f.startswith(tree + "/") for f in scanned), f"No files scanned under {tree}/"
    for required in ("app/main.py", "frontend/src/App.tsx", "README.md", "CONTRIBUTING.md", ".env.example",
                     "tests/test_language_policy.py"):
        assert required in scanned, f"{required} is not covered by the language check"
    assert not scanned & set(NOT_IN_SCOPE)


def test_no_unreviewed_turkish_text():
    counts, locations = turkish_lines()
    unexpected = counts - Counter(ALLOWED_LINES)
    report = [f"{path}:{locations[(path, line)][0]}: {ascii(line)[:120]}" for path, line in sorted(unexpected)]
    assert not unexpected, (
        "Text outside the English development standard (see CONTRIBUTING.md). Write it in English, "
        "or, for legitimate multilingual content, add a reviewed exception:\n" + "\n".join(report)
    )


def test_reviewed_exceptions_are_unchanged():
    counts, _ = turkish_lines()
    missing = Counter(ALLOWED_LINES) - counts
    report = [f"{path}: {ascii(line)[:120]}" for path, line in sorted(missing)]
    assert not missing, (
        "A reviewed exception line was changed or removed. The multilingual fixtures must stay "
        "unchanged; update ALLOWED_LINES only after review:\n" + "\n".join(report)
    )
    assert {path for path, _ in ALLOWED_LINES} <= set(EXCEPTION_REASONS)


def test_application_and_interface_text_has_no_exceptions():
    """
    System-generated text (API messages, AI disclaimers, prompts) and the user interface are
    English-only, without exceptions; only test fixtures may need multilingual input.
    """
    exception_paths = {path for path, _ in ALLOWED_LINES} | set(EXCEPTION_REASONS)
    assert all(path.startswith("tests/") for path in exception_paths), sorted(exception_paths)
