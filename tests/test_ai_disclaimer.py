# ── 3. New extractions ───────────────────────────────────────────────────────


async def test_new_extraction_stores_and_returns_the_english_disclaimer(
    client: AsyncClient, created_document: dict, issuer_headers: dict, async_db: AsyncSession
):
    r = await client.post(f"/documents/{created_document['id']}/extractions", headers=issuer_headers)
    assert r.status_code == 201, r.text
    body = r.json()
    assert set(body) == EXTRACTION_KEYS
    assert body["disclaimer"] == UNVERIFIED_DISCLAIMER
    stored = (await async_db.execute(text("SELECT disclaimer FROM legal_extractions WHERE id = :i"),
                                     {"i": body["id"]})).scalar_one()
    assert stored == UNVERIFIED_DISCLAIMER
    assert (await client.get(f"/extractions/{body['id']}", headers=issuer_headers)).json()["disclaimer"] == stored
    listed = (await client.get(f"/documents/{created_document['id']}/extractions", headers=issuer_headers)).json()
    assert next(e for e in listed if e["id"] == body["id"])["disclaimer"] == stored


