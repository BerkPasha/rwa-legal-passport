# Escaped so that this file stays free of Turkish letters (tests/test_language_policy.py)
TURKISH_LETTERS = re.compile("[\u00e7\u011f\u0131\u00f6\u015f\u00fc\u00c7\u011e\u0130\u00d6\u015e\u00dc]")
