import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { beforeEach, describe, expect, it } from 'vitest'
import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import { http, HttpResponse } from 'msw'
import { server } from './mocks/server'
import {
  BACKEND_AI_DISCLAIMER,
  BACKEND_APPROVAL_DISCLAIMER,
  BACKEND_PASSPORT_DISCLAIMER,
  MOCK_APPROVAL,
  MOCK_PASSPORT,
} from './mocks/handlers'
import { renderReview, reviewExtraction, serveReview, setReviewerSession } from './reviewFixtures'
import { DisclaimerBanner } from '../components/DisclaimerBanner'
import { ApprovalTypeBadge, PassportRightBadge, VERIFICATION_LEVEL_LABELS } from '../components/StatusBadge'
import { PassportPreview } from '../pages/PassportPreview'
import { AuthProvider } from '../AuthContext'
import type { LegalPassport } from '../types'

// Stage 9B-4, step 10: system text is English; stored records are shown exactly as stored.
// Escaped so that this file stays free of Turkish letters (tests/test_language_policy.py).
const TURKISH_LETTERS = /[\u00e7\u011f\u0131\u00f6\u015f\u00fc\u00c7\u011e\u0130\u00d6\u015e\u00dc]/
// The disclaimer stored with extractions created before step 10 (historical data, never rewritten)
const LEGACY_DISCLAIMER =
  'DO\u011eRULANMAMI\u015e AI TASLA\u011eI — Bu \u00e7\u0131kar\u0131m bir yapay zeka modeli taraf\u0131ndan ' +
  '\u00fcretilmi\u015ftir ve nitelikli bir hukuk profesyoneli taraf\u0131ndan incelenmemi\u015f ya da ' +
  'onaylanmam\u0131\u015ft\u0131r. Ba\u011f\u0131ms\u0131z uzman do\u011frulamas\u0131 yap\u0131lmadan herhangi bir hukuki, ' +
  'yat\u0131r\u0131m veya uyumluluk karar\u0131nda kullan\u0131lamaz.'

beforeEach(setReviewerSession)

describe('English AI disclaimer on the review page', () => {
  it('shows the backend disclaimer verbatim, separately from the quotation check and the approval', async () => {
    serveReview({ extractions: reviewExtraction() })
    renderReview()
    const banner = await screen.findByTestId('disclaimer-banner')
    expect(banner.textContent).toBe(BACKEND_AI_DISCLAIMER)
    expect(banner).toHaveTextContent('generated by an artificial intelligence model')
    expect(banner).toHaveTextContent('it does not confirm that the extracted value is correct')
    expect(banner).toHaveTextContent('None of these establishes legal validity, ownership or enforceability.')
    // The quotation check is its own indicator, and it is not called a verification
    expect(screen.getByTestId('evidence-badge-verified')).toHaveTextContent('Quote found on page 2')
    // The approval is described as an internal attestation, not a legal opinion
    expect(screen.getByText(/This approval is an internal attestation — it does not constitute a legally binding opinion\./))
      .toBeInTheDocument()
    expect(document.body.textContent).not.toMatch(TURKISH_LETTERS)
  })

  it('shows the disclaimer stored with an earlier extraction exactly as stored', async () => {
    serveReview({ extractions: reviewExtraction({ disclaimer: LEGACY_DISCLAIMER }) })
    renderReview()
    const banner = await screen.findByTestId('disclaimer-banner')
    expect(banner.textContent).toBe(LEGACY_DISCLAIMER)
    expect(banner.textContent).not.toBe(BACKEND_AI_DISCLAIMER)
  })

  it('shows the stored disclaimer of each approval record', async () => {
    const earlier = { ...MOCK_APPROVAL, id: 'appr-000', disclaimer: 'INTERNAL REVIEW ONLY — Earlier stored approval wording.' }
    serveReview({
      extractions: reviewExtraction({
        status: 'approved',
        approval_state: { state: 'current', version_is_current: true, current_approval_types: ['issuer_attestation'], reasons: [] },
      }),
      approvals: [MOCK_APPROVAL, earlier],
    })
    renderReview()
    expect(await screen.findByText(`${BACKEND_APPROVAL_DISCLAIMER.slice(0, 100)}…`)).toBeInTheDocument()
    expect(screen.getByText('INTERNAL REVIEW ONLY — Earlier stored approval wording.…')).toBeInTheDocument()
  })

  it('renders whatever disclaimer it is given, without a built-in replacement', () => {
    render(<DisclaimerBanner text="Any stored disclaimer text." />)
    expect(screen.getByTestId('disclaimer-banner').textContent).toBe('Any stored disclaimer text.')
  })
})

describe('Approval labels never present an attestation as legal validity', () => {
  it('labels the independent legal reviewer approval as a review', () => {
    render(<ApprovalTypeBadge type="legal_verification" />)
    expect(screen.getByTestId('approval-type-badge')).toHaveTextContent('Independent Legal Review')
    expect(screen.queryByText('Legal Verification')).not.toBeInTheDocument()
  })

  it('labels independent reviewer attestation without calling it verification', () => {
    render(<PassportRightBadge isUnknown={false} verified independentlyVerified conflict={false} />)
    expect(screen.getByTestId('passport-right-badge')).toHaveTextContent('Independent reviewer attested')
    expect(Object.values(VERIFICATION_LEVEL_LABELS).filter(l => /independently verified$/i.test(l)))
      .toEqual(['Issuer attested — not independently verified'])
  })

  it('shows an independently attested passport in the same terms', async () => {
    const attested: LegalPassport = {
      ...MOCK_PASSPORT,
      verification_level: 'independently_verified',
      legal_rights: [{ ...MOCK_PASSPORT.legal_rights[0], independently_verified: true, reviewer_attestation_status: 'independent_reviewer_attested' }],
      approvals: [{ ...MOCK_PASSPORT.approvals[0], approval_type: 'legal_verification', reviewer_role: 'independent_legal_reviewer' }],
      verification_summary: { ...MOCK_PASSPORT.verification_summary, independently_attested_field_count: 1 },
    }
    server.use(http.get('http://localhost:8000/passport/:network/:assetCode/:issuerKey', () => HttpResponse.json(attested)))
    render(<MemoryRouter><AuthProvider><PassportPreview /></AuthProvider></MemoryRouter>)
    await userEvent.type(screen.getByPlaceholderText('MRPROP'), 'MRPROP')
    await userEvent.type(screen.getByPlaceholderText('G…'), 'GABC1234')
    await userEvent.type(screen.getByPlaceholderText(/X-API-Key/i), 'test-inst-key-alpha')
    await userEvent.click(screen.getByRole('button', { name: /fetch legal passport/i }))
    const card = await screen.findByTestId('passport-card')
    expect(within(card).getByTestId('verification-level-badge')).toHaveTextContent('Attested by an independent legal reviewer')
    expect(within(card).getByTestId('passport-right-badge')).toHaveTextContent('Independent reviewer attested')
    expect(within(card).getByTestId('approval-type-badge')).toHaveTextContent('Independent Legal Review')
    expect(within(card).getByTestId('disclaimer-banner').textContent).toBe(BACKEND_PASSPORT_DISCLAIMER)
    expect(within(card).getByTestId('verification-meaning')).toHaveTextContent('Reviewer approvals are internal attestations, not legal opinions.')
    expect(card.textContent).not.toMatch(/Independently verified|Legal Verification/)
    expect(document.body.textContent).not.toMatch(TURKISH_LETTERS)
  })
})

describe('English-only interface', () => {
  it('declares English as the document language and has no language selector', async () => {
    const html = readFileSync(resolve(process.cwd(), 'index.html'), 'utf-8')
    expect(html).toMatch(/<html lang="en">/)
    serveReview({ extractions: reviewExtraction() })
    renderReview()
    await screen.findByTestId('disclaimer-banner')
    expect(screen.queryByRole('combobox', { name: /language/i })).not.toBeInTheDocument()
  })
})
