"""
AI Legal-Rights Extraction Service.

Uses the Anthropic Messages API to extract seven structured rights fields
from uploaded legal documents.

SECURITY RULES:
- The API key is never logged or shown in error messages.
- All outputs carry the "AI-generated draft" disclaimer (UNVERIFIED_DISCLAIMER).
- Legal validity is never confirmed.
- If evidence is insufficient, "unknown" is returned; nothing is fabricated.

OUTPUT INTEGRITY (Stage 9B-4, step 3):
- validate_ai_claims is the single structural gate for extraction output. The router applies
  it to the result of every AI service, real or mocked, before anything is stored.
- A legal field may appear only once. Any duplicate rejects the whole response: no claim is
  chosen, merged or overwritten.
- An unknown claim is stored in its canonical form: value "unknown", no page, no quotation.
- JSON is parsed strictly: repeated keys and NaN/Infinity are rejected, and page numbers and
  unknown flags are not coerced from other types.
- A truncated (max_tokens) or text-less response is invalid output.
"""

import json
import re
from collections import Counter
from collections.abc import Iterable
from datetime import datetime, timezone
from typing import Any, Optional

import anthropic
from pydantic import BaseModel, ValidationError

from app.enums import LegalFieldName
from app.schemas.extraction import AIExtractionResult, ClaimSource, RawClaim

# ── Constants ─────────────────────────────────────────────────────────────────

# Stored with every new extraction (legal_extractions.disclaimer); records created earlier keep
# the disclaimer they were created with (Stage 9B-4, step 10). It keeps four things apart: the AI
# output, the quotation check, reviewer attestation, and legal validity, which none of them
# establishes. It stays accurate after a later correction or approval.
UNVERIFIED_DISCLAIMER = (
    "AI-GENERATED DRAFT — The legal-rights values in this extraction were generated by an "
    "artificial intelligence model from the text of one uploaded document version. They are not "
    "legal advice and may be incomplete or incorrect. A quotation check confirms only that the "
    "quoted text appears on the cited page of that document version; it does not confirm that the "
    "extracted value is correct. Reviewer corrections and approvals are internal attestations, not "
    "legal opinions. None of these establishes legal validity, ownership or enforceability. Do not "
    "use this output for any legal, investment or compliance decision without review by qualified, "
    "independent legal counsel."
)

# Page markers of the model input (Stage 9B-4, step 10); the page text itself is passed unchanged
PAGE_MARKER = "=== PAGE {number} ==="
EMPTY_PAGE_TEXT = "(empty page)"
NO_TEXT_DOCUMENT = "(document contains no extractable text)"

_SYSTEM_PROMPT = """\
You are a legal document analyst for tokenized real-world asset (RWA) platforms.

Extract seven legal rights fields from the document provided and return ONLY a valid JSON object.

MANDATORY RULES — follow exactly:
1. Extract ONLY information explicitly stated in the document text.
2. Never infer, assume, or invent legal provisions.
3. If a field is absent or evidence is insufficient, set value to the exact string "unknown" and is_unknown to true.
4. For every known field (is_unknown = false), include a verbatim quote as supporting_passage: copy it character for character from a single page, without ellipses, paraphrasing or added words, and set page_number to the n of that page's "=== PAGE n ===" marker.
5. Return ONLY valid JSON — no markdown, no preamble, no explanation.

Fields to extract:
  ownership_nature      — Nature of investor ownership rights
  income_rights         — Income distribution and payment rights
  voting_rights         — Voting or governance rights
  redemption_rights     — Redemption terms and conditions
  transfer_restrictions — Restrictions on transfer of ownership
  jurisdiction          — Applicable legal jurisdiction
  insolvency_provisions — Insolvency or bankruptcy-related provisions

Required JSON structure (include all seven fields):
{
  "claims": [
    {
      "field": "ownership_nature",
      "value": "<extracted text>",
      "is_unknown": false,
      "source": { "page_number": 1, "supporting_passage": "<exact verbatim quote>" }
    },
    {
      "field": "voting_rights",
      "value": "unknown",
      "is_unknown": true,
      "source": null
    }
  ]
}\
"""


# ── Helper functions ──────────────────────────────────────────────────────────


def _format_pages(pages: list[dict]) -> str:
    """Converts the page list into the text block sent to the model."""
    if not pages:
        return NO_TEXT_DOCUMENT
    blocks = [
        f"{PAGE_MARKER.format(number=p['page_number'])}\n{p['text_content'] or EMPTY_PAGE_TEXT}"
        for p in pages
    ]
    return "\n\n".join(blocks)


def _reject_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict:
    """JSON object hook: a repeated key would otherwise silently keep only its last value."""
    keys = [key for key, _ in pairs]
    duplicates = sorted({key for key in keys if keys.count(key) > 1})
    if duplicates:
        raise ValueError(f"duplicate JSON keys: {', '.join(duplicates)}")
    return dict(pairs)


def _reject_constant(name: str) -> None:
    raise ValueError(f"invalid JSON constant: {name}")


def _extract_json_from_text(text: str) -> dict:
    """Strips markdown code fences from the response and parses the JSON strictly."""
    text = text.strip()
    match = re.search(r"```(?:json)?\s*([\s\S]+?)\s*```", text)
    if match:
        text = match.group(1).strip()
    return json.loads(text, object_pairs_hook=_reject_duplicate_keys, parse_constant=_reject_constant)


class _RawAIResponse(BaseModel):
    """Validation schema for the raw JSON structure returned by the AI."""
    claims: list[RawClaim]


# ── Output validation ─────────────────────────────────────────────────────────

INVALID_OUTPUT = "AI returned an invalid response format"
UNKNOWN_VALUE = "unknown"


class AIOutputValidationError(RuntimeError):
    """
    The AI output violates the extraction contract; nothing from the response is stored.
    A RuntimeError, so it follows the existing AI-error path (HTTP 503, no persistence).
    """


def _states_unknown(value: str) -> bool:
    # An empty value, or the word "unknown", asserts no legal fact
    return value.strip().rstrip(".").strip().casefold() in ("", UNKNOWN_VALUE)


def _canonical_unknown(field: LegalFieldName) -> RawClaim:
    return RawClaim(field=field, value=UNKNOWN_VALUE, is_unknown=True, source=None)


def validate_ai_claims(claims: Iterable[Any]) -> list[RawClaim]:
    """
    Validates and canonicalizes the claims of one AI response. Deterministic rules:
    1. Every claim is (re)validated against RawClaim, whatever service produced it.
    2. Each legal field may appear at most once. A duplicate, even with an identical value,
       rejects the whole response.
    3. An unknown claim is canonical: value "unknown", no source page, no quotation. A claim
       whose value is empty or "unknown" is unknown, whatever its flag says.
    4. Fields missing from the response are completed as canonical unknown claims.
    Returns one claim per legal field, in LegalFieldName order. Raises AIOutputValidationError.
    """
    try:
        parsed = [
            RawClaim.model_validate(claim.model_dump() if isinstance(claim, BaseModel) else claim)
            for claim in claims
        ]
    except Exception as exc:  # noqa: BLE001 — untrusted output; any malformed claim rejects the response
        raise AIOutputValidationError(f"{INVALID_OUTPUT}: {exc}") from exc

    counts = Counter(claim.field for claim in parsed)
    duplicates = sorted(field.value for field, count in counts.items() if count > 1)
    if duplicates:
        raise AIOutputValidationError(
            f"{INVALID_OUTPUT}: duplicate legal fields ({', '.join(duplicates)}). "
            "No claim of this response was stored."
        )

    by_field = {claim.field: claim for claim in parsed}
    validated: list[RawClaim] = []
    for field in LegalFieldName:
        claim = by_field.get(field)
        if claim is None or claim.is_unknown or _states_unknown(claim.value):
            validated.append(_canonical_unknown(field))
        else:
            validated.append(claim)
    return validated


def _response_text(response: Any) -> str:
    """Text of the model response; a truncated or text-less response is invalid output."""
    if getattr(response, "stop_reason", None) == "max_tokens":
        raise AIOutputValidationError(f"{INVALID_OUTPUT}: the response was truncated (max_tokens).")
    texts = [
        block.text
        for block in (getattr(response, "content", None) or [])
        if getattr(block, "type", None) == "text" and isinstance(getattr(block, "text", None), str)
    ]
    if not texts:
        raise AIOutputValidationError(f"{INVALID_OUTPUT}: the response contains no text.")
    return "".join(texts)


def _parse_and_complete(raw_text: str, model: str) -> AIExtractionResult:
    """
    Parses the AI response text and returns a validated AIExtractionResult; the claims pass
    validate_ai_claims (duplicates rejected, unknown claims canonical, missing fields unknown).
    Raises AIOutputValidationError.
    """
    try:
        raw_dict = _extract_json_from_text(raw_text)
        parsed = _RawAIResponse.model_validate(raw_dict)
    except (ValueError, ValidationError, KeyError, TypeError) as exc:
        raise AIOutputValidationError(f"{INVALID_OUTPUT}: {exc}") from exc

    return AIExtractionResult(
        claims=validate_ai_claims(parsed.claims),
        ai_model=model,
        extraction_timestamp=datetime.now(timezone.utc),
        disclaimer=UNVERIFIED_DISCLAIMER,
    )


# ── Service class ─────────────────────────────────────────────────────────────


class AnthropicAIService:
    """
    Performs legal-rights extraction with the Anthropic Claude model.
    In tests this class is replaced with a mock — no real API call is made.
    """

    def __init__(self, api_key: str, model: str) -> None:
        self._client = anthropic.AsyncAnthropic(api_key=api_key)
        self._model = model

    async def extract_legal_rights(
        self,
        document_id: str,
        version_id: str,
        pages: list[dict],
    ) -> AIExtractionResult:
        """
        Extracts the seven legal-rights fields from the document pages.
        Raises RuntimeError on failure (the API key is never included).
        """
        user_message = (
            f"Extract legal rights from this document.\n\n"
            f"Document ID: {document_id}\n\n"
            f"{_format_pages(pages)}"
        )

        try:
            response = await self._client.messages.create(
                model=self._model,
                max_tokens=4096,
                system=_SYSTEM_PROMPT,
                messages=[{"role": "user", "content": user_message}],
            )
        except anthropic.AuthenticationError:
            raise RuntimeError(
                "AI service: authentication failed. Check the API key configuration."
            )
        except anthropic.RateLimitError:
            raise RuntimeError(
                "AI service: rate limit exceeded. Please try again later."
            )
        except anthropic.APIConnectionError:
            # Connection errors and timeouts, after the SDK's own retries are exhausted;
            # they carry no HTTP status
            raise RuntimeError(
                "AI service: connection failed. Please try again later."
            ) from None
        except anthropic.APIError as exc:
            # Internal error details are not passed to the client
            status_code = getattr(exc, "status_code", None)
            raise RuntimeError(
                f"AI service: request failed (HTTP {status_code})." if status_code
                else "AI service: request failed."
            ) from exc

        return _parse_and_complete(_response_text(response), self._model)


# ── FastAPI dependency ────────────────────────────────────────────────────────


def get_ai_service() -> AnthropicAIService:
    """Default AI service — replaced with a mock in tests."""
    from app.config import settings
    return AnthropicAIService(
        api_key=settings.anthropic_api_key,
        model=settings.ai_model,
    )
